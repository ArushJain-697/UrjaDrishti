"""Regenerate the results block in README.md from results/*.json. Never type a number by hand."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
pct = lambda v, d=1: f"{v * 100:.{d}f}%"
NAMES = {"RCR_S1": "Raichur solar", "KLB_S1": "Kalaburagi solar", "BGK_W1": "Bagalkot wind",
         "DVG_W1": "Davanagere wind", "BE_LIM_S": "Limburg solar (measured)", "BE_OFF_W": "Belgian offshore wind (measured)",
         "PVG_S1": "Pavagada", "KPL_S1": "Koppal"}
BASES = ("nwp_ensemble", "linear_mos", "nwp_ecmwf", "nwp_gfs", "nwp_icon")
LABEL = {"nwp_ensemble": "average of 3 weather models", "linear_mos": "linear MOS",
         "nwp_ecmwf": "ECMWF", "nwp_gfs": "GFS", "nwp_icon": "ICON"}


def sealed() -> list[str]:
    s = json.loads((R / "v3_sealed.json").read_text())
    out = ["### Sealed tests, scored once", "",
           "Four Karnataka sites that no model or design choice had seen, Apr 2025 – Oct 2026, forecasts as available at "
           "the real filing deadline:", "",
           "| Site | Model nMAE | Best baseline (nMAE) | vs best | P10–P90 coverage | RED-hour coverage | Hours marked RED |",
           "|---|---|---|---|---|---|---|"]
    for sid, v in s["spatial"].items():
        base = {k: v[k]["nmae"] for k in BASES}
        bn = min(base, key=base.get)
        m = v["model"]
        out.append(f"| {NAMES[sid]} | **{pct(m['nmae'], 2)}** | {LABEL[bn]} ({pct(base[bn], 2)}) | **−{pct(1 - m['nmae'] / base[bn])}** | "
                   f"{pct(m['coverage_80'])} | {pct(m['red_coverage'])} | {pct(m['red_share_hours'], 0)} |")
    out += ["", "Measured output from the Belgian grid operator Elia, Nov 2025 – Oct 2026, against Elia's own day-ahead "
            "forecast issued at 11:00 the day before:", "",
            "| Series | Model nMAE | Elia nMAE | Linear MOS nMAE | Quantile score model / Elia | P10–P90 coverage model / Elia |",
            "|---|---|---|---|---|---|"]
    for sid, v in s["elia_test"].items():
        m, e = v["model"], v["elia_dayahead"]
        out.append(f"| {NAMES[sid]} | {pct(m['nmae'], 2)} | **{pct(e['nmae'], 2)}** | {pct(v['linear_mos']['nmae'], 2)} | "
                   f"{m['qs3']:.4f} / {e['qs3']:.4f} | {pct(m['coverage_80'])} / {pct(e['coverage_80'])} |")
    return out + [""]


def tiers() -> list[str]:
    t = json.loads((R / "tiers_dev.json").read_text())
    out = ["### Tiers and the Flat-Band Trap (development years)", "",
           "| Period · technology | Hours GREEN / AMBER / RED | RED share of out-of-band energy | RED-hour coverage, one band for all hours | RED-hour coverage, per tier |",
           "|---|---|---|---|---|"]
    for period, kinds in t["periods"].items():
        for kind, v in kinds.items():
            tm, tg = v["model"]["tiers"], v["global_conformal"]["tiers"]
            share = " / ".join(pct(tm[k]["share_hours"], 0) for k in ("GREEN", "AMBER", "RED"))
            out.append(f"| {period} · {kind} | {share} | **{pct(tm['RED']['share_dsm_excess'], 0)}** | "
                       f"{pct(tg['RED']['coverage_80'])} | **{pct(tm['RED']['coverage_80'])}** |")
    return out + [""]


def checks() -> list[str]:
    d = json.loads((R / "v3_dev.json").read_text())
    ld = d["lead"]
    out = ["### Development checks", "", "| Check | Solar | Wind |", "|---|---|---|"]
    cells = [f"{pct(ld['day1']['test'][k]['nmae'], 2)} → {pct(ld['filed']['test'][k]['nmae'], 2)}" for k in ("solar", "wind")]
    out.append(f"| Error with a ~24 h lead → with the real 10:00 filing deadline (Nov 2025 – Oct 2026) | {cells[0]} | {cells[1]} |")
    for sid, v in d["second_truth"].items():
        out.append(f"| {NAMES[sid]}: model vs average of 3 weather models, scored on ERA5 / on NASA POWER satellite data | "
                   f"{pct(v['era5']['model_p50'], 2)} vs {pct(v['era5']['nwp_ensemble'], 2)} / "
                   f"{pct(v['nasa']['model_p50'], 2)} vs {pct(v['nasa']['nwp_ensemble'], 2)} | – |")
    st = list(d["second_truth"].values())
    out.append(f"| How far ERA5 and NASA POWER disagree with each other (nMAE) | "
               f"{pct(min(x['truths_agree_nmae'] for x in st))}–{pct(max(x['truths_agree_nmae'] for x in st))} | – |")
    return out + [""]


def main():
    lines = sealed() + tiers() + checks()
    block = "<!-- numbers:start (generated by scripts/readme_numbers.py; do not edit) -->\n" + "\n".join(lines) + "<!-- numbers:end -->"
    readme = ROOT / "README.md"
    txt = readme.read_text()
    txt = re.sub(r"<!-- numbers:start.*?<!-- numbers:end -->", lambda _: block, txt, flags=re.S)
    readme.write_text(txt)
    print(block)


if __name__ == "__main__":
    main()
